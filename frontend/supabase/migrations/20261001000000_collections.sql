-- Этап 6: SEO-подборки. Подборка = сохранённый набор фильтров каталога
-- (строка адреса, например «chan=1&drive=60») + заголовок и вводный текст ru/kk.
create table public.collections (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title_ru text not null check (length(trim(title_ru)) > 0),
  title_kk text,
  intro_ru text,
  intro_kk text,
  filters text not null default '',
  -- Порядок на главной и в списках: меньше — выше. На главной — первые 4.
  sort_order int not null default 100,
  published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger collections_set_updated_at
  before update on public.collections
  for each row execute function public.set_updated_at();

alter table public.collections enable row level security;

create policy "Подборки: публичное чтение"
  on public.collections for select
  to anon, authenticated
  using (published);

