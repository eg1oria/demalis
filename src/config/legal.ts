// Реквизиты и контакты сайта: подвал, «О нас», «Контакты», политика,
// соглашение, оферта. ЗАПОЛНИ ПЕРЕД ЗАПУСКОМ РЕКЛАМЫ: всё, что начинается
// с «[ЗАПОЛНИТЬ», видно на сайте как есть. Данные должны совпадать с тем,
// что указано в Google Ads и при верификации рекламодателя (docs/SEO.md).
export const LEGAL = {
  /** Кто владеет сайтом: «ИП Фамилия Имя Отчество» или «ТОО «Название»». */
  operator: "[ЗАПОЛНИТЬ: ИП Фамилия Имя Отчество или ТОО «Название»]",
  /** ИИН (для ИП) или БИН (для ТОО) — 12 цифр. */
  bin: "[ЗАПОЛНИТЬ: ИИН/БИН, 12 цифр]",
  /** Юридический адрес, как в регистрационных документах. */
  address: "[ЗАПОЛНИТЬ: город, улица, дом, офис]",
  /** Телефон для связи с сайтом, формат +7XXXXXXXXXX. */
  phone: "[ЗАПОЛНИТЬ: +7XXXXXXXXXX]",
  /** Email для гостей, владельцев и вопросов по персональным данным. */
  email: "[ЗАПОЛНИТЬ: email@домен]",
  /** Номер WhatsApp, формат +7XXXXXXXXXX (можно тот же, что телефон). */
  whatsapp: "[ЗАПОЛНИТЬ: +7XXXXXXXXXX]",
  /** Telegram: @username без ссылки. */
  telegram: "[ЗАПОЛНИТЬ: @username]",
  /** Когда отвечаете, например «ежедневно 10:00–20:00 (Алматы)». */
  hours: "[ЗАПОЛНИТЬ: часы работы]",
  /** Где физически хранится база (регион Supabase), например «Германия, Франкфурт». */
  storage: "[ЗАПОЛНИТЬ: страна и город серверов базы данных]",
  /** Сколько хранятся заявки гостей, например «1 год». */
  leadsRetention: "[ЗАПОЛНИТЬ: срок, например 1 год]",
  /** Возврат за платные тарифы, например «за неиспользованные полные недели». */
  refund:
    "[ЗАПОЛНИТЬ: условия возврата, например «деньги за неиспользованные полные недели тарифа возвращаем в течение 10 рабочих дней»]",
  /** Что проверяете перед плашкой «Проверено» (через «|»). */
  verifiedChecks:
    "[ЗАПОЛНИТЬ: например, созвонились с владельцем и сверили телефон]|[ЗАПОЛНИТЬ: например, сверили фото и адрес по видеозвонку или на месте]",
  /** Дата последней редакции юридических страниц (ГГГГ-ММ-ДД). */
  updated: "2026-10-18",
} as const;

export type LegalKey = keyof typeof LEGAL;

/** Заполнено ли поле (не заглушка «[ЗАПОЛНИТЬ: …]» и не пусто). */
export function isFilled(value: string): boolean {
  return value.trim() !== "" && !value.includes("[ЗАПОЛНИТЬ");
}

/** Подстановка {site}, {operator}, {email}… в тексты юридических страниц. */
export function fillLegal(text: string, site: string): string {
  return text
    .replaceAll("{site}", site)
    .replace(/\{(\w+)\}/g, (match, key: string) =>
      key in LEGAL ? LEGAL[key as LegalKey] : match,
    );
}

/** Только цифры и «+» — для tel: и wa.me. */
export const phoneDigits = (phone: string) => phone.replace(/[^\d+]/g, "");
