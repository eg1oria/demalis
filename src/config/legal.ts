export type LegalKey = keyof typeof LEGAL;

/** Заполнено ли поле (не заглушка «[ЗАПОЛНИТЬ: …]» и не пусто). */
export function isFilled(value: string): boolean {
  return value.trim() !== "" && !value.includes("[ЗАПОЛНИТЬ");
}

/** Подстановка {site}, {operator}, {email}… в тексты юридических страниц. */
export function fillLegal(text: string, site: string): string {
  return text
    .replaceAll("{site}", site)
    .replace(/\{(\w+)\}/g, (match, key: string) =>
      key in LEGAL ? LEGAL[key as LegalKey] : match,
    );
}

/** Только цифры и «+» — для tel: и wa.me. */
export const phoneDigits = (phone: string) => phone.replace(/[^\d+]/g, "");
